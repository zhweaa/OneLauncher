#Requires -Version 5.1
<#
.SYNOPSIS
Generates white PNG icons and updates icon resources in the Avalonia theme dictionary.
.DESCRIPTION
Run on Windows: pwsh -File scripts/Generate-ThemeIcons.ps1
Reads OneLauncher/Assets/icos/*.png, preserves dimensions and every alpha byte,
and writes white variants to icos/white plus the marked icon blocks in Styles/Theme.axaml.
Run again after adding or updating icons. No image tools or packages are required.
#>
[CmdletBinding()]
param(
    [string] $ProjectRoot = (Join-Path $PSScriptRoot '..')
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$iconDirectory = Join-Path $ProjectRoot 'OneLauncher/Assets/icos'
$whiteDirectory = Join-Path $iconDirectory 'white'
$dictionaryPath = Join-Path $ProjectRoot 'OneLauncher/Styles/Theme.axaml'
$themeText = [System.IO.File]::ReadAllText($dictionaryPath)
$newline = if ($themeText.Contains("`r`n")) { "`r`n" } else { "`n" }
$themePatterns = @{}
foreach ($theme in @('Light', 'Dark')) {
    $pattern = '(?ms)^[ \t]*<!-- BEGIN GENERATED ICONS: ' + $theme + ' -->\r?\n.*?^[ \t]*<!-- END GENERATED ICONS: ' + $theme + ' -->'
    if ([regex]::Matches($themeText, $pattern).Count -ne 1) {
        throw "Expected exactly one generated icon block for $theme in $dictionaryPath"
    }
    $themePatterns[$theme] = $pattern
}
$icons = @(Get-ChildItem -LiteralPath $iconDirectory -Filter '*.png' -File | Sort-Object Name)
if ($icons.Count -eq 0) {
    throw "No PNG icons found in $iconDirectory"
}

# Use the filename to derive stable resource keys, e.g. settings1.png -> IconSettings1.
$keys = @{}
foreach ($icon in $icons) {
    if ($icon.BaseName -cnotmatch '^[a-zA-Z][a-zA-Z0-9]*$') {
        throw "Icon filenames must contain only letters and digits: $($icon.Name)"
    }
    $key = 'Icon' + $icon.BaseName.Substring(0, 1).ToUpperInvariant() + $icon.BaseName.Substring(1)
    if ($keys.ContainsKey($key)) {
        throw "Duplicate icon resource key: $key"
    }
    $keys[$key] = $icon.Name
}

[System.IO.Directory]::CreateDirectory($whiteDirectory) | Out-Null
foreach ($icon in $icons) {
    $original = [System.Drawing.Bitmap]::new($icon.FullName)
    $white = $null
    try {
        $bounds = [System.Drawing.Rectangle]::new(0, 0, $original.Width, $original.Height)
        $white = $original.Clone($bounds, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        $pixels = $white.LockBits($bounds, [System.Drawing.Imaging.ImageLockMode]::ReadWrite,
            [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        try {
            # GDI+ uses BGRA bytes. Change only RGB; retain alpha and antialiased edges.
            $row = [byte[]]::new($white.Width * 4)
            for ($y = 0; $y -lt $white.Height; $y++) {
                $rowAddress = [System.IntPtr]::Add($pixels.Scan0, $y * $pixels.Stride)
                [System.Runtime.InteropServices.Marshal]::Copy($rowAddress, $row, 0, $row.Length)
                for ($x = 0; $x -lt $row.Length; $x += 4) {
                    $row[$x] = $row[$x + 1] = $row[$x + 2] = 255
                }
                [System.Runtime.InteropServices.Marshal]::Copy($row, 0, $rowAddress, $row.Length)
            }
        }
        finally {
            $white.UnlockBits($pixels)
        }
        $white.Save((Join-Path $whiteDirectory $icon.Name), [System.Drawing.Imaging.ImageFormat]::Png)
    }
    finally {
        if ($null -ne $white) { $white.Dispose() }
        $original.Dispose()
    }
}

# Replace only the marked icon blocks; leave all hand-maintained theme resources intact.
foreach ($theme in @('Light', 'Dark')) {
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('            <!-- BEGIN GENERATED ICONS: ' + $theme + ' -->')
    $lines.Add('            <!-- Generated by scripts/Generate-ThemeIcons.ps1. -->')
    foreach ($icon in $icons) {
        $key = 'Icon' + $icon.BaseName.Substring(0, 1).ToUpperInvariant() + $icon.BaseName.Substring(1)
        $relativePath = if ($theme -eq 'Dark') { 'white/' + $icon.Name } else { $icon.Name }
        $lines.Add('            <Bitmap x:Key="' + $key + '">avares://OneLauncher/Assets/icos/' + $relativePath + '</Bitmap>')
    }
    $lines.Add('            <!-- END GENERATED ICONS: ' + $theme + ' -->')
    $block = $lines -join $newline
    $themeText = [regex]::Replace($themeText, $themePatterns[$theme],
        [System.Text.RegularExpressions.MatchEvaluator] { param($match) $block })
}
[System.IO.File]::WriteAllText($dictionaryPath, $themeText, [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated $($icons.Count) white icons and updated icon resources in $dictionaryPath"
